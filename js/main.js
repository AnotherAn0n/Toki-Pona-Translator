const convertToArr = (textInput, split = " ") => {
	return textInput.split(split);
};

const convertWordToEmoji = (word) => {
	const wordLC = word.toLowerCase().replace(".", "");
	const isValidWord = tp[wordLC] != undefined;
	const hasDotInside = word.includes(".");
	if (isValidWord && !hasDotInside) {
		return tp[wordLC]["emoji"];
	} else if (isValidWord && hasDotInside) {
		return `${tp[wordLC]["emoji"]}. `;
	} else {
		return;
	}
};

const convertEmojiToWord = (input) => {
	let returnedWord;
	if (input != " " && input != ".") {
		for (const word in tp) {
			if (tp[word].emoji == input) {
				returnedWord = word;
			}
		}
		const isValidEmoji = returnedWord != "";
		toReturn = returnedWord.replace(" ", "");
		if (isValidEmoji) {
			return `${toReturn} `;
		}
	} else if (input == ".") {
		return input;
	} else {
		return;
	}
};

const latinToEmoji = (latinText) => {
	const latinArr = convertToArr(latinText);
	let emojiText = "";
	latinArr.forEach((char) => {
		emojiText += convertWordToEmoji(char);
	});
	return emojiText;
};

